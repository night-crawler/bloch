pub trait ColumnWriter {
    fn type_name(&self) -> Cow<'static, str>;
    fn write_prefix(&self, out: &mut dyn Write) -> io::Result<()>;
    fn write_data(&self, out: &mut dyn Write) -> io::Result<()>;
    fn data_len(&self) -> usize;
    fn push_default(&mut self);
    fn flush(&mut self) -> Result<()> {
        Ok(())
    }
    fn reserve(&mut self, rows: usize);
    fn clear(&mut self);
}

pub trait ValueWriter: ColumnWriter {
    type Value<'a>: 'a;
    fn write(&mut self, value: Self::Value<'_>) -> Result<()>;

    fn write_slice(&mut self, values: &[Self::Value<'_>]) -> Result<()>
    where
        for<'a> Self::Value<'a>: Copy,
    {
        for &value in values {
            self.write(value)?;
        }
        Ok(())
    }
}

/// A column writer built from a reader of the same column type.
pub trait FromReader<'a, R: TryRead<'a>>: ColumnWriter {
    fn from_reader(reader: &R) -> Self;
    fn write_item(&mut self, item: R::Item) -> Result<()>;
}

/// The default writer for a reader type.
/// Pick another [`FromReader`] per column with `#[col(writer = ...)]`.
pub trait DefaultWriter<'a>: TryRead<'a> {
    type Writer: FromReader<'a, Self>;
}

pub trait FixedWidth {
    type Value<'a>: 'a;

    fn type_name(&self) -> Cow<'static, str>;

    fn width(&self) -> usize;

    /// Appends the encoding of the default value, 0 bytes by default.
    fn push_default(&self, data: &mut Vec<u8>) {
        data.resize(data.len() + self.width(), 0);
    }

    /// Appends exactly [`Self::width`] bytes, or fails without touching `data`.
    fn write(&self, value: Self::Value<'_>, data: &mut Vec<u8>) -> Result<()>;
}

#[derive(Default)]
pub struct FixedWidthColumn<T: FixedWidth> {
    ty: T,
    data: Vec<u8>,
}

impl<T: FixedWidth> FixedWidthColumn<T> {
    pub const fn new(ty: T) -> Self {
        Self {
            ty,
            data: Vec::new(),
        }
    }

    pub fn with_capacity(ty: T, rows: usize) -> Self {
        let data = Vec::with_capacity(rows * ty.width());
        Self { ty, data }
    }

    pub const fn ty(&self) -> &T {
        &self.ty
    }
}

impl<T: FixedWidth> From<T> for FixedWidthColumn<T> {
    fn from(ty: T) -> Self {
        Self::new(ty)
    }
}

impl<T: FixedWidth> ColumnWriter for FixedWidthColumn<T> {
    fn type_name(&self) -> Cow<'static, str> {
        self.ty.type_name()
    }

    fn write_prefix(&self, _out: &mut dyn Write) -> io::Result<()> {
        Ok(())
    }

    fn write_data(&self, out: &mut dyn Write) -> io::Result<()> {
        out.write_all(&self.data)
    }

    fn data_len(&self) -> usize {
        self.data.len()
    }

    fn push_default(&mut self) {
        self.ty.push_default(&mut self.data);
    }

    fn reserve(&mut self, rows: usize) {
        self.data.reserve(rows * self.ty.width());
    }

    fn clear(&mut self) {
        self.data.clear();
    }
}

impl<T: FixedWidth> ValueWriter for FixedWidthColumn<T> {
    type Value<'a> = T::Value<'a>;

    fn write(&mut self, value: T::Value<'_>) -> Result<()> {
        self.ty.write(value, &mut self.data)
    }
}

/// The `*Writer` struct generated by `#[derive(WriteBlock)]` with a [`ColumnWriter`] per column.
pub trait RowWriter {
    const NUM_COLUMNS: usize;

    fn reserve(&mut self, rows: usize);
    fn clear(&mut self);
    /// Sum of every column's [`ColumnWriter::data_len`].
    fn data_len(&self) -> usize;
    fn flush(&mut self) -> Result<()>;
    fn encode(&self, rows: usize, out: &mut dyn Write) -> io::Result<()>;
}

/// A row of a block: the `*Item` struct generated by `#[derive(FromBlock)]`, or the `*Row`
/// struct of [`ValueWriter`] values generated by `#[derive(WriteBlock)]`.
pub trait Row: Sized {
    type Reader;
    type Writer: RowWriter;

    /// A row writer with the reader's column type parameters.
    fn writer(reader: &Self::Reader) -> Self::Writer;

    /// Appends one value to every column.
    fn write(self, writer: &mut Self::Writer) -> Result<()>;
}

impl<A: RowWriter, B: RowWriter> RowWriter for (A, B) {
    const NUM_COLUMNS: usize = A::NUM_COLUMNS + B::NUM_COLUMNS;

    fn reserve(&mut self, rows: usize) {
        self.0.reserve(rows);
        self.1.reserve(rows);
    }

    fn clear(&mut self) {
        self.0.clear();
        self.1.clear();
    }

    fn data_len(&self) -> usize {
        self.0.data_len() + self.1.data_len()
    }

    fn flush(&mut self) -> Result<()> {
        self.0.flush()?;
        self.1.flush()
    }

    fn encode(&self, rows: usize, out: &mut dyn Write) -> io::Result<()> {
        self.0.encode(rows, out)?;
        self.1.encode(rows, out)
    }
}

impl<A: Row, B: Row> Row for (A, B) {
    type Reader = (A::Reader, B::Reader);
    type Writer = (A::Writer, B::Writer);

    fn writer(reader: &Self::Reader) -> Self::Writer {
        (A::writer(&reader.0), B::writer(&reader.1))
    }

    fn write(self, writer: &mut Self::Writer) -> Result<()> {
        self.0.write(&mut writer.0)?;
        self.1.write(&mut writer.1)
    }
}

/// Lifetime-erased marker for a `Variant` enum: the enum itself, the column writer of each
/// element, and their ClickHouse type names.
pub trait VariantValue {
    /// A fixed type name instead of `Variant(..)`, e.g. `Geometry`.
    const TYPE_NAME: Option<&'static str> = None;

    type Value<'a>: 'a;

    /// A tuple with one column writer per element.
    type Columns: ColumnWriter;

    /// One type name per element, in declaration order.
    fn type_names(columns: &Self::Columns) -> Vec<Cow<'static, str>>;
}

/// An enum written into a `Variant` column. ClickHouse orders the elements by type name, so the
/// enum's variants must be declared in that order; Geometry types are the fixed-order exception.
pub trait IntoVariant<'a>: FromVariant<'a> {
    type Marker: VariantValue;

    fn columns(readers: &Self::Readers) -> <Self::Marker as VariantValue>::Columns;

    fn write(self, columns: &mut <Self::Marker as VariantValue>::Columns) -> Result<u8>;
}

pub fn encode_column(
    name: &str,
    writer: &dyn ColumnWriter,
    num_rows: usize,
    out: &mut dyn Write,
) -> io::Result<()> {
    let type_name = writer.type_name();
    let mut header = Vec::with_capacity(name.len() + type_name.len() + 4);
    write_string(name.as_bytes(), &mut header);
    write_string(type_name.as_bytes(), &mut header);
    out.write_all(&header)?;
    if num_rows != 0 {
        writer.write_prefix(out)?;
        writer.write_data(out)?;
    }
    Ok(())
}

pub(crate) fn write_varuint(mut value: u64, out: &mut Vec<u8>) {
    while value >= 0x80 {
        out.push((value.to_le_bytes()[0] & 0x7f) | 0x80);
        value >>= 7;
    }
    out.push(value.to_le_bytes()[0]);
}

fn write_string(value: &[u8], out: &mut Vec<u8>) {
    write_varuint(value.len() as u64, out);
    out.extend_from_slice(value);
}

fn write_le<T: Copy, const N: usize>(
    values: &[T],
    to_bytes: impl Fn(T) -> [u8; N],
    out: &mut dyn Write,
) -> io::Result<()> {
    const CHUNK: usize = 4096;
    let mut buf = [0u8; CHUNK];
    for chunk in values.chunks(CHUNK / N) {
        for (slot, value) in buf.chunks_exact_mut(N).zip(chunk) {
            slot.copy_from_slice(&to_bytes(*value));
        }
        out.write_all(&buf[..chunk.len() * N])?;
    }
    Ok(())
}

fn write_offsets(offsets: &[u64], out: &mut dyn Write) -> io::Result<()> {
    write_le(offsets, u64::to_le_bytes, out)
}

fn write_quoted(value: &str, out: &mut String) {
    out.push('\'');
    for c in value.chars() {
        if matches!(c, '\'' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('\'');
}
