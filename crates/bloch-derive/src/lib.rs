use proc_macro_crate::{FoundCrate, crate_name};
use proc_macro2::TokenStream as TokenStream2;
use quote::{ToTokens as _, format_ident, quote};
use syn::punctuated::Punctuated;
use syn::spanned::Spanned as _;
use syn::token::Comma;
use syn::{
    Attribute, Data, DeriveInput, Expr, Field, Fields, Ident, Lifetime, Variant, parse::Parse,
    parse_macro_input, parse_quote,
};

struct ColSpec {
    ident: syn::Ident,
    ty: syn::Type,
    vis: syn::Visibility,
    index: usize,
    /// Expression evaluating to `&str`: the `#[col(name = ...)]` value, or a
    /// string literal of the field identifier.
    name: TokenStream2,
    /// `#[col(writer = ...)]`: the column writer type instead of the reader's default.
    writer: Option<syn::Type>,
}

/// Derives `bloch::reader::FromBlock` for a named struct of column readers.
///
/// The reader struct must implement `Copy` and `Clone`, usually via
/// `#[derive(FromBlock, Copy, Clone)]`. This macro does not implement either
/// trait, so manual implementations can avoid unnecessary generic bounds.
///
/// Fields look up their identifier, or the `#[col(name = ...)]` override, in
/// the source. Each field independently selects the first matching column,
/// including in named tuples; repeated names do not consume successive occurrences.
/// Unnamed tuples are read positionally, in field declaration order.
///
/// # Example
///
/// ```ignore
/// use bloch::reader::{Array, I64, Map, Str};
/// use bloch::{FromBlock, ParsedBlock};
///
/// const ID_COLUMN: &str = "id";
///
/// #[derive(FromBlock, Copy, Clone)]
/// struct MapRow<'a> {
///     #[col(name = ID_COLUMN)]
///     id: I64<'a>,
///     #[col(name = "arr_map")]
///     maps: Array<'a, Map<'a, Str<'a>, Str<'a>>>,
/// }
///
/// fn read(block: &ParsedBlock<'_>) -> bloch::Result<()> {
///     let mut total_pairs = 0;
///     for (row_index, row) in MapRow::rows(block)?.enumerate() {
///         let row = row?;
///         assert_eq!(row.id, i64::try_from(row_index)?);
///         for map in row.maps {
///             total_pairs += map?.count();
///         }
///     }
///     assert!(total_pairs > 0);
///     Ok(())
/// }
/// ```
#[proc_macro_derive(FromBlock, attributes(col))]
pub fn derive_from_block(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);

    derive_from_block_inner(&input)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

/// Derives `bloch::writer::Row` for the item generated by `FromBlock` and for `FooRow`.
///
/// Add `WriteBlock` alongside `FromBlock` on a named struct of column readers. The derive
/// generates `FooWriter` (one column writer per field, `bloch::writer::RowWriter`), implements
/// `Row` for the existing `FooItem`, and generates `FooRow`: the same columns as
/// `bloch::writer::ValueWriter` values (`&str`, `Option<..>`, slices for arrays and maps), so
/// rows need no parsed block. `FooRow` is `Copy` whenever every value is.
///
/// ```ignore
/// let mut writer = BlockWriter::<FooWriter>::new(); // or BlockWriter::from_reader(&foo)
/// writer.write(FooItem { id: 1, name: "x", tags: array_iter })?;
/// writer.write(FooRow { id: 2, name: "y", tags: &["a", "b"] })?;
/// let mut block = Vec::new();
/// writer.encode(&mut block)?;
/// ```
///
/// Each field's writer is its reader's `bloch::writer::DefaultWriter::Writer`, or the
/// `#[col(writer = ...)]` type, which must implement `bloch::writer::FromReader` for the
/// reader. `FooWriter` stores only column columns, not the input lifetime or reader types,
/// so each `write` may borrow a different short-lived input. Its column-writer type parameters
/// have defaults for schemas without type or const parameters; generic schemas infer them.
/// `FooWriter` is `Default` when no column type needs runtime parameters such as a
/// `FixedString` length; otherwise build the writer with `BlockWriter::from_reader`.
#[proc_macro_derive(WriteBlock, attributes(col))]
pub fn derive_write_block(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);

    derive_write_block_inner(&input)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

/// Derives `bloch::reader::FromVariant` for an enum representing one ClickHouse `Variant` value.
///
/// # Example
///
/// ```ignore
/// use bloch::reader::{Array, ArrayIter, I64, TryRead as _, Variant};
/// use bloch::FromVariant;
///
/// // This order matches Variant(Array(Int64), Int64, String).
/// #[derive(FromVariant)]
/// enum Value<'a> {
///     #[col(reader = Array<'a, I64<'a>>)]
///     Array(ArrayIter<'a, I64<'a>>),
///     Integer(i64),
///     String(&'a str),
/// }
///
/// let reader: Variant<Value<'_>> = Variant::try_from(mark)?;
/// match reader.try_read(row_index)? {
///     Value::Array(values) => println!("{:?}", values.try_collect_vec()?),
///     Value::Integer(value) => println!("{value}"),
///     Value::String(value) => println!("{value}"),
/// }
/// ```
#[proc_macro_derive(FromVariant, attributes(col))]
pub fn derive_from_variant(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);

    derive_from_variant_inner(&input)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

